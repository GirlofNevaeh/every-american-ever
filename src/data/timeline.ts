export const PRESIDENT_STEPS: TimeStep[] = PRESIDENCY.map((slot) => {
  const person = getPresident(slot.slug)!;
  const term = person.terms[person.numbers.indexOf(slot.number)] ?? person.terms[0];
  const current = term.end === null;
  const extra =
    person.numbers.length > 1
      ? ` He ${person.died ? "was" : "is"} also the ${person.numbers
          .filter((n) => n !== slot.number)
          .map(ordinal)
          .join(" and ")} president.`
      : "";
  const restated = /\d+(st|nd|rd|th) president/.test(person.facts[0]) ? person.facts[1] : person.facts[0];
  return {
    id: `p-${slot.number}`,
    era: "now",
    kicker: ordinal(slot.number),
    title: person.name,
    body: `${person.name} ${current ? "is" : "was"} the ${ordinal(slot.number)} president, ${termLabel(term)}.${extra} ${restated}`,
    kind: "presidents",
    href: `/presidents/${person.slug}?n=${slot.number}`,
    hrefLabel: "Open this page",
    portrait: person.slug,
  };
});
